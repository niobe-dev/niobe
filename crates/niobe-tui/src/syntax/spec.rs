//! How each language writes the things a highlighter tells apart: one table
//! per language, which the lexer is driven by.
//!
//! A table starts from [`BASE`], a language with nothing in it, and names
//! only what its language has. The keyword lists are the languages' reserved
//! words and the few contextual ones written where a reserved word would be;
//! a list is a lookup, not a parse, so a word a language reserves only in
//! one position is left out rather than coloured everywhere else.

/// How a language is read: by the lexer for code, or by a reader of its own.
#[derive(Debug, Clone, Copy)]
pub(super) enum Grammar {
    /// Code, read by the table-driven lexer.
    Code(&'static Spec),
    /// Tags and their attributes: HTML, XML, SVG.
    Markup,
    /// A unified diff, read a whole line at a time.
    Diff,
}

/// A way a language writes a string: what opens it, what closes it, whether
/// a backslash escapes the character after it and whether it can run past the
/// end of its line. One that cannot ends there, closed or not, so a quote
/// left open by mistake colours one line rather than the rest of the file.
#[derive(Debug, Clone, Copy)]
pub(super) struct Quote {
    pub(super) open: &'static str,
    pub(super) close: &'static str,
    pub(super) escapes: bool,
    pub(super) multiline: bool,
}

const fn quote(open: &'static str, escapes: bool, multiline: bool) -> Quote {
    Quote {
        open,
        close: open,
        escapes,
        multiline,
    }
}

/// What a language's `#` opens, where it is not a comment.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) enum Hash {
    /// Nothing of its own.
    Nothing,
    /// A preprocessor directive, as the first thing on its line: C's
    /// `#include`.
    Directive,
    /// A directive anywhere: Swift's `#if` and `#selector`.
    Anywhere,
    /// An attribute in brackets: Rust's `#[derive(…)]` and `#![…]`.
    Bracketed,
}

/// What makes a word a key a value is written under.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) enum Keys {
    /// Nothing does.
    Nothing,
    /// A `:` after it, as JSON and YAML write a key; not `::`.
    Colon,
    /// An `=` after it, as TOML and INI write a key; not `==`.
    Equals,
}

/// How one language writes its code.
#[derive(Debug, Clone, Copy)]
pub(super) struct Spec {
    /// What starts a comment that runs to the end of its line.
    pub(super) line_comments: &'static [&'static str],
    /// Whether a line comment starts only at the start of a line or after a
    /// blank, as in a shell, where `a#b` is one word.
    pub(super) comment_after_blank: bool,
    /// What opens and closes a block comment, checked before
    /// [`Spec::line_comments`], since Lua's `--[[` starts with its `--`.
    pub(super) block_comments: &'static [(&'static str, &'static str)],
    /// Whether a block comment inside another has to be closed before the
    /// outer one is.
    pub(super) nested_comments: bool,
    /// The strings, the longest opening first, since `"""` starts with `"`.
    pub(super) quotes: &'static [Quote],
    /// The words written right before a quote that make it a string of
    /// another kind — Python's `f` and `rb`, Miri's `re` — and part of it.
    pub(super) string_prefixes: &'static [&'static str],
    /// Whether `r"…"` and `r#"…"#` are raw strings, closed by a quote and as
    /// many hashes as opened them.
    pub(super) raw_strings: bool,
    /// Whether `'` opens a character only where one character and a `'`
    /// follow, and is otherwise a lifetime or a label, as Rust's `'a`.
    pub(super) lifetimes: bool,
    /// The language's reserved words.
    pub(super) keywords: &'static [&'static str],
    /// Its built-in types.
    pub(super) types: &'static [&'static str],
    /// The values it names: `true`, `nil`, `self`.
    pub(super) constants: &'static [&'static str],
    /// The words after which the next word names a function being declared.
    pub(super) function_intros: &'static [&'static str],
    /// The words after which the next word names a type being declared.
    pub(super) type_intros: &'static [&'static str],
    /// Whether its words are the same word in any case, as SQL's.
    pub(super) case_insensitive: bool,
    /// Whether a word that starts with a capital names a type.
    pub(super) capitals_are_types: bool,
    /// Whether a word right before `(` names a function being called.
    pub(super) calls_are_functions: bool,
    /// Whether a word right before `!` is a macro being called, as Rust's.
    pub(super) bang_macros: bool,
    /// What a word may hold besides letters, digits and `_`: CSS's `-`,
    /// Ruby's `?` and `!`.
    pub(super) word_extra: &'static str,
    /// What a word may start with besides a letter and `_`: JavaScript's `$`.
    pub(super) word_start_extra: &'static str,
    /// What marks the word after it as a variable: a shell's `$`.
    pub(super) sigils: &'static str,
    /// Whether `@word` is an annotation on what follows.
    pub(super) decorators: bool,
    /// What `#` opens where it is not a comment.
    pub(super) hash: Hash,
    /// Whether `:word` is a symbol, as Ruby's and Elixir's.
    pub(super) symbols: bool,
    /// What makes a word a key.
    pub(super) keys: Keys,
    /// Whether `[section]` at the start of a line names a section, as in
    /// TOML and INI.
    pub(super) sections: bool,
    /// Whether `<<WORD` opens a heredoc, whose lines up to the one that is
    /// `WORD` alone are its body, as a shell's: without it, a `'` in the
    /// body's prose opens a string that runs past the heredoc's end.
    pub(super) heredocs: bool,
}

