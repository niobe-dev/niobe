//! The Homebrew formula a release is installed with, written from the archives
//! the release published.
//!
//! The formula is not kept in this repository: it lives in the tap, and the
//! release workflow commits it there. It is generated from the SHA-256 file
//! that sits beside each archive in the release, so the formula and the
//! archives are the same release by construction, and a target whose checksum
//! is not there fails the task rather than leaving a formula that installs
//! nothing on that machine.

use std::collections::BTreeMap;
use std::path::Path;

/// Where the archives are published.
const RELEASES: &str = "https://github.com/niobe-dev/niobe/releases/download";

/// The targets a release builds for, in the order the formula lists them: the
/// Homebrew block each is in and the CPU it is for.
const TARGETS: [(&str, &str, &str); 4] = [
    ("aarch64-apple-darwin", "on_macos", "on_arm"),
    ("x86_64-apple-darwin", "on_macos", "on_intel"),
    ("aarch64-unknown-linux-musl", "on_linux", "on_arm"),
    ("x86_64-unknown-linux-musl", "on_linux", "on_intel"),
];

/// `niobe formula <version> <directory>`: prints the formula for `version`,
/// from the `niobe-<target>.tar.gz.sha256` files in `directory`.
pub fn run(args: &[String]) -> Result<(), String> {
    let [version, directory] = args else {
        return Err("usage: cargo xtask formula <version> <directory of .sha256 files>".to_owned());
    };
    let mut sums = BTreeMap::new();
    for (target, _, _) in TARGETS {
        let file = Path::new(directory).join(format!("niobe-{target}.tar.gz.sha256"));
        let text = std::fs::read_to_string(&file)
            .map_err(|error| format!("cannot read {}: {error}", file.display()))?;
        let sum =
            checksum(&text).ok_or_else(|| format!("{} does not hold a SHA-256", file.display()))?;
        sums.insert(target, sum);
    }
    print!("{}", render(version, &sums)?);
    Ok(())
}

/// The digest `shasum -a 256` wrote: sixty-four hex digits, then the name.
fn checksum(text: &str) -> Option<String> {
    let first = text.split_whitespace().next()?;
    (first.len() == 64 && first.bytes().all(|b| b.is_ascii_hexdigit()))
        .then(|| first.to_ascii_lowercase())
}

/// The formula text for `version`, with `sums` the digest of each target's
/// archive.
fn render(version: &str, sums: &BTreeMap<&str, String>) -> Result<String, String> {
    let version = version.strip_prefix('v').unwrap_or(version);
    if version.is_empty() || !version.bytes().all(|b| b.is_ascii_digit() || b == b'.') {
        return Err(format!("`{version}` is not a release version"));
    }
    let mut out = String::new();
    out.push_str("# Generated by `cargo xtask formula` from the checksums a release\n");
    out.push_str("# published; the release workflow commits it here. Do not edit by hand.\n");
    out.push_str("class Niobe < Formula\n");
    out.push_str(
        "  desc \"Terminal coding agent that keeps you aware of what is being built and how\"\n",
    );
    out.push_str("  homepage \"https://github.com/niobe-dev/niobe\"\n");
    out.push_str(&format!("  version \"{version}\"\n"));
    out.push_str("  license \"Apache-2.0\"\n");
    for block in ["on_macos", "on_linux"] {
        out.push_str(&format!("\n  {block} do\n"));
        for (target, _, cpu) in TARGETS.iter().filter(|(_, owner, _)| *owner == block) {
            let sum = sums
                .get(target)
                .ok_or_else(|| format!("no checksum for {target}"))?;
            out.push_str(&format!("    {cpu} do\n"));
            out.push_str(&format!(
                "      url \"{RELEASES}/v{version}/niobe-{target}.tar.gz\"\n"
            ));
            out.push_str(&format!("      sha256 \"{sum}\"\n"));
            out.push_str("    end\n");
        }
        out.push_str("  end\n");
    }
    out.push_str("\n  def install\n    bin.install \"niobe\"\n  end\n");
    out.push_str("\n  test do\n");
    out.push_str("    assert_match version.to_s, shell_output(\"#{bin}/niobe --version\")\n");
    out.push_str("  end\nend\n");
    Ok(out)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn sums() -> BTreeMap<&'static str, String> {
        TARGETS
            .iter()
            .enumerate()
            .map(|(at, (target, _, _))| (*target, format!("{at:064x}")))
            .collect()
    }

    #[test]
    fn the_formula_names_each_archive_with_the_digest_published_beside_it() {
        let formula = render("0.17.0", &sums()).expect("every target has a digest");

        assert!(formula.contains("version \"0.17.0\""), "{formula}");
        for (at, (target, _, _)) in TARGETS.iter().enumerate() {
            let url = format!("{RELEASES}/v0.17.0/niobe-{target}.tar.gz");
            let sum = format!("{at:064x}");
            let found = formula
                .lines()
                .position(|line| line.trim() == format!("url \"{url}\""))
                .unwrap_or_else(|| panic!("no url for {target}:\n{formula}"));
            assert_eq!(
                formula.lines().nth(found + 1).map(str::trim),
                Some(format!("sha256 \"{sum}\"").as_str()),
                "the digest under {target}'s url:\n{formula}"
            );
        }
    }

    #[test]
    fn each_cpu_is_in_the_block_of_its_system_and_the_formula_tests_the_version() {
        let formula = render("v0.17.0", &sums()).expect("a leading v is the tag's");

        let macos = formula.find("on_macos do").expect("a macOS block");
        let linux = formula.find("on_linux do").expect("a Linux block");
        assert!(macos < linux);
        let darwin_arm = formula.find("aarch64-apple-darwin").expect("darwin arm");
        let linux_arm = formula
            .find("aarch64-unknown-linux-musl")
            .expect("linux arm");
        assert!((macos..linux).contains(&darwin_arm), "{formula}");
        assert!(linux_arm > linux, "{formula}");
        assert!(formula.contains("bin.install \"niobe\""));
        assert!(formula.contains("shell_output(\"#{bin}/niobe --version\")"));
        assert!(!formula.contains("depends_on"), "claude is not Homebrew's");
    }

    #[test]
    fn a_target_with_no_digest_is_an_error_and_not_a_formula_that_installs_nothing() {
        let mut missing = sums();
        missing.remove("x86_64-apple-darwin");

        let error = render("0.17.0", &missing).expect_err("a target has no digest");

        assert!(error.contains("x86_64-apple-darwin"), "{error}");
    }

    #[test]
    fn a_version_that_is_not_one_is_refused() {
        for version in ["", "latest", "0.17.0\"; system \"rm"] {
            assert!(render(version, &sums()).is_err(), "{version}");
        }
    }

    #[test]
    fn a_digest_is_the_first_word_of_what_shasum_wrote() {
        let line = format!("{}  niobe-x86_64-apple-darwin.tar.gz\n", "AB".repeat(32));

        assert_eq!(checksum(&line), Some("ab".repeat(32)));
        assert_eq!(checksum("not a digest  file\n"), None);
        assert_eq!(checksum(""), None);
    }
}
